for(const c of [/func advance\(/,/func current\(/,/func resolve\(/,/DataRegistry\.entities\("travel_events"\)/,/travel_event\.triggered/,/travel_event\.resolved/])assert.match(travelEvents,c);
const regionalMap=await read('godot/map/regional_map_view.gd');
for(const c of [/Camera2D/,/func _input\(/,/func _process\(delta: float\)/,/InputEventScreenTouch/,/InputEventScreenDrag/,/_input_counts/,/_update_party\(/,/_update_camera_follow\(/,/follow_party/,/MapAssetLoader\.background/,/Diagnostics\.register_provider/])assert.match(regionalMap,c);
assert.doesNotMatch(regionalMap,/_simulation\.step\(|_travel\.tick\(|_travel\.arrive\(/);
const bootstrap=await read('godot/app/bootstrap.gd');
for(const c of [/NOTIFICATION_WM_GO_BACK_REQUEST/,/game_shell\.handle_back\(\)/,/exit_confirmation/,/status\.show_message\("Мир загружен"\)/,/_handle_shell_back\(/,/_return_from_aux_screen\(/])assert.match(bootstrap,c);
const gameShell=await read('godot/ui/game_shell.gd');
for(const c of [/signal back_requested/,/func handle_back\(/,/func toggle_system_menu\(/,/func active_screen\(/,/ui\.system_menu/])assert.match(gameShell,c);
const toast=await read('godot/ui/toast.gd');
for(const c of [/func show_message\(/,/create_timer\(/,/func clear\(/])assert.match(toast,c);
const scene=await read('godot/app/bootstrap.tscn');
for(const c of [/name="MainMenu"/,/type="CenterContainer" parent="MainMenu"/,/name="BottomNav"/,/name="SystemMenu"/,/name="Character"/,/name="Inventory"/,/name="Journal"/,/name="Settings"/,/name="SaveBrowser"/])assert.match(scene,c);
for(const c of [/name="MapSurface" type="SubViewportContainer"/,/name="MapViewport" type="SubViewport" parent="MapSurface"/,/parent="MapSurface\/MapViewport\/RegionalMap\/Viewport"/,/name="Pause" type="Button"/,/name="Camp" type="Button"/,/name="Follow" type="Button"/,/name="Detail" type="Label"/,/stretch = true/])assert.match(scene,c);
assert.match(bootstrap,/bind_map_view\(map_surface, regional_map\)/);
assert.match(bootstrap,/map_viewport\.push_input\(event, false\)/);
const mapViewportContainer=await read('godot/map/map_viewport_container.gd');
assert.match(mapViewportContainer,/func _propagate_input_event\(_event: InputEvent\) -> bool:[\s\S]*return false/);
assert.match(regionalMap,/func set_input_active\(active: bool\)/);
assert.match(regionalMap,/_reset_gesture_state\(\)/);
assert.match(regionalMap,/NOTIFICATION_APPLICATION_FOCUS_OUT/);
assert.equal((scene.match(/name="MainMenu" type="Button" parent="GameShell\/SystemMenu\/Content"/g)||[]).length,1);
assert.doesNotMatch(scene,/parent="GameShell\/Layout\/ContentHost\/Screens\/Character\/Body"[\s\S]{0,160}script = ExtResource\("10"\)/);
assert.match(scene,/name="ExitDialog" type="ConfirmationDialog"/);
assert.match(scene,/res:\/\/ui\/safe_area\.gd/);
const settings=await read('godot/ui/settings_screen.gd');
for(const c of [/_add_section\(/,/PanelContainer\.new\(\)/,/Служебные инструменты/])assert.match(settings,c);
