const travelState=await read('godot/travel/travel_state.gd');
for(const c of [/func start\(/,/func tick\(/,/func make_camp\(/,/func break_camp\(/,/func commit_arrival\(/,/func progress\(/])assert.match(travelState,c);
const travelModule=await read('godot/travel/travel_module.gd');
for(const c of [/func preview_to\(/,/func begin_to\(/,/func make_camp\(/,/func break_camp\(/,/_world\.current_position\(\)/,/travel\.origin_mismatch/,/travel\.arrival_committed/,/_world\.enter_map_point\(/])assert.match(travelModule,c);
const simulationRuntime=await read('godot/simulation/simulation_runtime.gd');
for(const c of [/_simulation\.step\(/,/_travel\.tick\(/,/_travel_events\.advance\(/,/_travel\.arrive\(/])assert.match(simulationRuntime,c);
